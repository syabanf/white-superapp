/** Monday-to-Sunday week around `week` (any day, "YYYY-MM-DD"), never past the current week. */
export function weekRange(week: string | undefined, today: string): { from: string; to: string; prev: string; next: string | null } {
  const iso = (d: Date) => d.toISOString().slice(0, 10);
  const parse = (v: string) => new Date(`${v}T00:00:00Z`);
  const anchor = week && /^\d{4}-\d{2}-\d{2}$/.test(week) && week <= today ? parse(week) : parse(today);
  const monday = new Date(anchor);
  monday.setUTCDate(anchor.getUTCDate() - ((anchor.getUTCDay() + 6) % 7));
  const sunday = new Date(monday);
  sunday.setUTCDate(monday.getUTCDate() + 6);
  const prev = new Date(monday);
  prev.setUTCDate(monday.getUTCDate() - 7);
  const next = new Date(monday);
  next.setUTCDate(monday.getUTCDate() + 7);
  return { from: iso(monday), to: iso(sunday), prev: iso(prev), next: iso(next) <= today ? iso(next) : null };
}
