/** Label for a value set entry, falling back to the raw value. */
export function lbl(map: Record<string, string>, v: string | null | undefined): string {
  if (!v) return ss.dash;
  return map[v] ?? v;
}

/** Options for selects from a label map. */
export function opts(map: Record<string, string>) {
  return Object.entries(map).map(([value, label]) => ({ value, label }));
}

